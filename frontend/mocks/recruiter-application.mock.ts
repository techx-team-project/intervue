const BASE_TIMESTAMP = Date.parse('2026-10-19T04:00:00Z');
const DAY_MS = 86_400_000;
export const MOCK_RECRUITER_NAME = 'Lê Thu Hà';

function isoDaysAgo(days: number, hourOffset = 0): string {
  return new Date(BASE_TIMESTAMP - days * DAY_MS + hourOffset * 3_600_000).toISOString();
}

function toAsciiSlug(name: string): string {
  return name
    .normalize('NFD')
    .replace(/[\u0300-\u036f]/g, '')
    .replace(/đ/g, 'd')
    .replace(/Đ/g, 'D')
    .replace(/\s+/g, '-');
}

function formatVietnameseDate(iso: string): string {
  const date = new Date(iso);
  return `${String(date.getUTCDate()).padStart(2, '0')}/${String(date.getUTCMonth() + 1).padStart(2, '0')}/${date.getUTCFullYear()}`;
}

