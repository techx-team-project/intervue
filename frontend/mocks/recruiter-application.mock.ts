function buildScreeningAnswers(jobId: string, answers: string[] | undefined): ScreeningAnswer[] {
  const job = MOCK_RECRUITER_JOB_POSTS.find((item) => item.id === jobId);
  if (!job || !answers) return [];

  return job.screeningQuestions.slice(0, answers.length).map((question, index) => ({
    questionId: question.id,
    question: question.question,
    answer: answers[index],
    required: question.required,
  }));
}

function buildStatusHistory(seed: ApplicationSeed) {
  const activeIndex = ACTIVE_APPLICATION_STATUSES.indexOf(seed.status);
  const path =
    activeIndex >= 0
      ? ACTIVE_APPLICATION_STATUSES.slice(0, activeIndex + 1)
      : [
          ...ACTIVE_APPLICATION_STATUSES.slice(
            0,
            Math.max(1, ACTIVE_APPLICATION_STATUSES.indexOf(seed.closedFromStatus ?? 'IN_REVIEW') + 1),
          ),
          seed.status,
        ];

  const spanDays = Math.max(1, seed.appliedDaysAgo - seed.lastActivityDaysAgo);
  const stepDays = spanDays / Math.max(1, path.length - 1);

  return path.map((status, index) => ({
    id: `${seed.id}-history-${index + 1}`,
    from: index === 0 ? undefined : path[index - 1],
    to: status,
    changedBy: index === 0 || status === 'WITHDRAWN' ? seed.fullName : MOCK_RECRUITER_NAME,
    changedAt: isoDaysAgo(seed.appliedDaysAgo - stepDays * index),
    reason: status === 'REJECTED' || status === 'NO_AGREEMENT' ? seed.rejection?.reason : undefined,
  }));
}

function buildApplication(seed: ApplicationSeed): RecruiterApplication {
  const job = MOCK_RECRUITER_JOB_POSTS.find((item) => item.id === seed.jobId);
  const appliedAt = isoDaysAgo(seed.appliedDaysAgo);
  const lastActivityAt = isoDaysAgo(seed.lastActivityDaysAgo);
  return {
    id: seed.id,
    jobId: seed.jobId,
    jobTitle: job ? job.title : 'Tin tuyển dụng đã xoá',
    candidate: {
      id: `${seed.id}-candidate`,
      fullName: seed.fullName,
      title: seed.title,
      location: seed.location,
      experienceYears: seed.experienceYears,
      topSkills: seed.topSkills,
      email: seed.email,
      phone: seed.phone,
    },
    status: seed.status,
    source: seed.source ?? 'DIRECT',
    appliedAt,
    lastActivityAt,
    isSaved: seed.isSaved ?? false,
    savedAt: seed.isSaved ? isoDaysAgo(seed.lastActivityDaysAgo, 2) : undefined,
    isViewed: seed.isViewed ?? seed.status !== 'APPLIED',
    cv: {
      id: `${seed.id}-cv`,
      fileName: `CV-${toAsciiSlug(seed.fullName)}.pdf`,
      fileSize: '248 KB',
      uploadedAt: formatVietnameseDate(appliedAt),
      isDefault: true,
      atsScore: seed.atsScore,
      downloadUrl: '#',
    },
    coverLetter: seed.coverLetter,
    screeningAnswers: buildScreeningAnswers(seed.jobId, seed.screeningAnswers),
    aiMatch: {
      score: seed.aiScore,
      summary: seed.aiSummary,
      matchedEvidence: seed.matchedEvidence,
      missingInformation: seed.missingInformation ?? [],
      askMoreAbout: seed.askMoreAbout ?? [],
      model: 'intervue-match-v1',
      evaluatedAt: isoDaysAgo(seed.appliedDaysAgo, 1),
    },
    internalNotes: (seed.internalNotes ?? []).map((content, index) => ({
      id: `${seed.id}-note-${index + 1}`,
      authorName: MOCK_RECRUITER_NAME,
      content,
      createdAt: isoDaysAgo(seed.lastActivityDaysAgo, index + 1),
    })),
    statusHistory: buildStatusHistory(seed),
    interview: seed.interview,
    rejection: seed.rejection,
  };
}

