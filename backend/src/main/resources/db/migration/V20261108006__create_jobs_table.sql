CREATE TABLE jobs (
    id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
    recruiter_id BIGINT UNSIGNED NOT NULL,
    company_id BIGINT UNSIGNED NOT NULL,
    company_name VARCHAR(255) NOT NULL,
    title VARCHAR(150) NOT NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'DRAFT',
    level VARCHAR(20) NULL,
    contract_type VARCHAR(20) NULL,
    working_arrangement VARCHAR(20) NULL,
    city VARCHAR(100) NULL,
    address VARCHAR(500) NULL,
    latitude DECIMAL(9, 6) NULL,
    longitude DECIMAL(9, 6) NULL,
    salary_negotiable TINYINT(1) NOT NULL DEFAULT 0,
    salary_min BIGINT UNSIGNED NULL,
    salary_max BIGINT UNSIGNED NULL,
    salary_currency VARCHAR(3) NULL,
    description TEXT NULL,
    requirements TEXT NULL,
    benefits TEXT NULL,
    application_mode VARCHAR(20) NOT NULL DEFAULT 'CV_ONLY',
    openings INT UNSIGNED NOT NULL DEFAULT 1,
    deadline DATE NULL,
    published_at TIMESTAMP NULL,
    created_at TIMESTAMP NOT NULL,
    updated_at TIMESTAMP NOT NULL,
    CONSTRAINT fk_jobs_recruiter FOREIGN KEY (recruiter_id) REFERENCES recruiters (id),
    CONSTRAINT fk_jobs_company FOREIGN KEY (company_id) REFERENCES companies (id),
    INDEX idx_jobs_status_published (status, published_at),
    INDEX idx_jobs_status_deadline (status, deadline),
    INDEX idx_jobs_company_status (company_id, status),
    INDEX idx_jobs_recruiter_status_updated (recruiter_id, status, updated_at),
    INDEX idx_jobs_city (city)
);

CREATE TABLE job_skills (
    job_id BIGINT UNSIGNED NOT NULL,
    skill_id BIGINT UNSIGNED NOT NULL,
    PRIMARY KEY (job_id, skill_id),
    CONSTRAINT fk_job_skills_job FOREIGN KEY (job_id) REFERENCES jobs (id) ON DELETE CASCADE,
    CONSTRAINT fk_job_skills_skill FOREIGN KEY (skill_id) REFERENCES skills (id),
    INDEX idx_job_skills_skill (skill_id)
);
