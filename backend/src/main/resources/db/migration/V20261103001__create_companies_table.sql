CREATE TABLE companies (
    id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
    name VARCHAR(255) NOT NULL,
    trading_name VARCHAR(255) NULL,
    tax_code VARCHAR(20) NOT NULL,
    business_type VARCHAR(20) NOT NULL,
    industry VARCHAR(150) NULL,
    website VARCHAR(255) NULL,
    market VARCHAR(150) NULL,
    target_customers VARCHAR(150) NULL,
    size VARCHAR(30) NULL,
    email VARCHAR(255) NULL,
    phone VARCHAR(20) NULL,
    address VARCHAR(500) NULL,
    description TEXT NULL,
    benefits TEXT NULL,
    logo_public_id VARCHAR(255) NULL,
    verification_status VARCHAR(20) NOT NULL DEFAULT 'UNVERIFIED',
    verified_at TIMESTAMP NULL,
    created_at TIMESTAMP NOT NULL,
    updated_at TIMESTAMP NOT NULL,
    CONSTRAINT uq_companies_tax_code UNIQUE (tax_code),
    INDEX idx_companies_verification_status (verification_status),
    INDEX idx_companies_name (name)
);
