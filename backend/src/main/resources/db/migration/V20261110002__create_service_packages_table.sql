CREATE TABLE service_packages (
    id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
    category_id BIGINT UNSIGNED NOT NULL,
    code VARCHAR(50) NOT NULL,
    slug VARCHAR(120) NOT NULL,
    name VARCHAR(150) NOT NULL,
    short_description VARCHAR(1000) NULL,
    price BIGINT UNSIGNED NOT NULL,
    currency CHAR(3) NOT NULL DEFAULT 'VND',
    badge VARCHAR(20) NOT NULL DEFAULT 'NONE',
    vip_ribbon TINYINT(1) NOT NULL DEFAULT 0,
    accent_color VARCHAR(20) NULL,
    hero_image_url VARCHAR(500) NULL,
    validity_days INT UNSIGNED NULL,
    bonus_credits INT UNSIGNED NOT NULL DEFAULT 0,
    one_time_per_company TINYINT(1) NOT NULL DEFAULT 0,
    status VARCHAR(20) NOT NULL DEFAULT 'DRAFT',
    display_order INT UNSIGNED NOT NULL DEFAULT 0,
    created_at TIMESTAMP NOT NULL,
    updated_at TIMESTAMP NOT NULL,
    CONSTRAINT fk_service_packages_category FOREIGN KEY (category_id) REFERENCES service_categories (id),
    UNIQUE KEY uk_service_packages_code (code),
    UNIQUE KEY uk_service_packages_slug (slug),
    INDEX idx_service_packages_category_status (category_id, status, display_order)
);
