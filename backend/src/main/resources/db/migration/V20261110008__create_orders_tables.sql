CREATE TABLE orders (
    id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
    code VARCHAR(20) NOT NULL,
    company_id BIGINT UNSIGNED NOT NULL,
    purchased_by_recruiter_id BIGINT UNSIGNED NOT NULL,
    status VARCHAR(30) NOT NULL DEFAULT 'PENDING_PAYMENT',
    subtotal BIGINT UNSIGNED NOT NULL,
    discount_amount BIGINT UNSIGNED NOT NULL DEFAULT 0,
    subtotal_after_discount BIGINT UNSIGNED NOT NULL,
    vat_rate DECIMAL(5, 4) NOT NULL,
    vat_amount BIGINT UNSIGNED NOT NULL,
    total_amount BIGINT UNSIGNED NOT NULL,
    paid_amount BIGINT UNSIGNED NOT NULL DEFAULT 0,
    currency CHAR(3) NOT NULL DEFAULT 'VND',
    expires_at TIMESTAMP NOT NULL,
    paid_at TIMESTAMP NULL,
    cancelled_at TIMESTAMP NULL,
    created_at TIMESTAMP NOT NULL,
    updated_at TIMESTAMP NOT NULL,
    CONSTRAINT fk_orders_company FOREIGN KEY (company_id) REFERENCES companies (id),
    CONSTRAINT fk_orders_recruiter FOREIGN KEY (purchased_by_recruiter_id) REFERENCES recruiters (id),
    UNIQUE KEY uk_orders_code (code),
    INDEX idx_orders_company_created (company_id, created_at),
    INDEX idx_orders_status_expires (status, expires_at)
);

CREATE TABLE order_items (
    id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
    order_id BIGINT UNSIGNED NOT NULL,
    package_id BIGINT UNSIGNED NULL,
    package_code VARCHAR(50) NOT NULL,
    package_name VARCHAR(150) NOT NULL,
    unit_price BIGINT UNSIGNED NOT NULL,
    quantity INT UNSIGNED NOT NULL,
    line_total BIGINT UNSIGNED NOT NULL,
    validity_days INT UNSIGNED NULL,
    bonus_credits INT UNSIGNED NOT NULL DEFAULT 0,
    benefits_json TEXT NULL,
    created_at TIMESTAMP NOT NULL,
    updated_at TIMESTAMP NOT NULL,
    CONSTRAINT fk_order_items_order FOREIGN KEY (order_id) REFERENCES orders (id) ON DELETE CASCADE,
    CONSTRAINT fk_order_items_package FOREIGN KEY (package_id) REFERENCES service_packages (id) ON DELETE SET NULL,
    INDEX idx_order_items_order (order_id)
);
