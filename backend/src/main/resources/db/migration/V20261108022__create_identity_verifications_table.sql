CREATE TABLE identity_verifications (
    id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
    user_id BIGINT UNSIGNED NOT NULL,
    status VARCHAR(20) NOT NULL,
    full_name VARCHAR(120) NOT NULL,
    date_of_birth DATE NOT NULL,
    id_number_hash CHAR(64) NOT NULL,
    id_number_last4 CHAR(4) NOT NULL,
    front_public_id VARCHAR(255) NOT NULL,
    back_public_id VARCHAR(255) NOT NULL,
    selfie_public_id VARCHAR(255) NOT NULL,
    submitted_at TIMESTAMP NOT NULL,
    reviewed_at TIMESTAMP NULL,
    reviewed_by BIGINT UNSIGNED NULL,
    reject_reason VARCHAR(500) NULL,
    rejection_count INT UNSIGNED NOT NULL DEFAULT 0,
    attempt_limit INT UNSIGNED NOT NULL DEFAULT 5,
    created_at TIMESTAMP NOT NULL,
    updated_at TIMESTAMP NOT NULL,
    CONSTRAINT fk_identity_verifications_user FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE CASCADE,
    UNIQUE KEY uq_identity_verifications_user (user_id),
    INDEX idx_identity_verifications_status_submitted (status, submitted_at),
    INDEX idx_identity_verifications_id_number (id_number_hash)
);
