CREATE TABLE interviews (
    id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
    application_id BIGINT UNSIGNED NOT NULL,
    candidate_id BIGINT UNSIGNED NOT NULL,
    company_id BIGINT UNSIGNED NOT NULL,
    scheduled_by BIGINT UNSIGNED NOT NULL,
    starts_at TIMESTAMP NOT NULL,
    duration_minutes INT NOT NULL,
    format VARCHAR(20) NOT NULL,
    location VARCHAR(500) NOT NULL,
    note VARCHAR(1000) NULL,
    status VARCHAR(30) NOT NULL,
    proposed_starts_at TIMESTAMP NULL,
    candidate_message VARCHAR(500) NULL,
    cancel_reason VARCHAR(500) NULL,
    reminder_24h_sent BOOLEAN NOT NULL DEFAULT FALSE,
    reminder_1h_sent BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMP NOT NULL,
    updated_at TIMESTAMP NOT NULL,
    CONSTRAINT fk_interviews_application FOREIGN KEY (application_id) REFERENCES applications (id) ON DELETE CASCADE,
    INDEX idx_interviews_application (application_id, created_at),
    INDEX idx_interviews_candidate (candidate_id, starts_at),
    INDEX idx_interviews_company (company_id, status, starts_at),
    INDEX idx_interviews_reminders (status, starts_at)
);
